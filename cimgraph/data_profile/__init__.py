"""
Deprecated home of the CIM profiles, kept for code written before cim-graph 0.6.

The profiles and the object model they are built on (Identity, CIMUnit, profile
merging) now ship in the separate ``cimprofiles`` package. Import from there:

    import cimprofiles.cim18.cimhub_2026 as cim
    from cimprofiles.identity import Identity

The object-model modules below are aliased, not copied: the old and new names are
the same module object. That matters because they carry module state (the pint
``ureg`` registry, ``ARCHIVE_JSON_LD``) and the ``Identity`` base class, which must
exist exactly once. Profiles generated by CIMTool before 2.3.1 import
``cimgraph.data_profile.identity`` and ``cimgraph.data_profile.units``, so these
aliases stay for all of 1.x. The profile packages themselves (``cim17v40`` etc.)
are re-export shims, removed in 1.0.
"""
import sys

import cimprofiles.identity
import cimprofiles.merge
import cimprofiles.units.cim_units.unit_multiplier
import cimprofiles.units.cim_units.unit_symbol
import cimprofiles.units.units
from cimprofiles import CIM_PROFILE, identity, merge, units

_ALIASED_MODULES = ('cimprofiles.identity', 'cimprofiles.merge', 'cimprofiles.units')

# Alias every loaded submodule too: aliasing only the units package would let
# `import cimgraph.data_profile.units.units` load units.py a second time.
for _name, _module in list(sys.modules.items()):
    if _name in _ALIASED_MODULES or _name.startswith(tuple(m + '.' for m in _ALIASED_MODULES)):
        sys.modules['cimgraph.data_profile' + _name[len('cimprofiles'):]] = _module
